
CREATE OR REPLACE VIEW VW_REVENUE_KPIS AS

WITH ORDER_TOTALS AS (
    SELECT
        O.ORDER_ID,
        O.ORDER_DATE,
        O.STATUS AS ORDER_STATUS,
        SUM(OI.QUANTITY) AS ITEMS_SOLD,
        SUM(OI.QUANTITY * OI.UNIT_PRICE)
            AS ORDER_REVENUE
    FROM ECOMMERCE_DB.STAGING.STG_ORDERS O

    LEFT JOIN ECOMMERCE_DB.STAGING.STG_ORDER_ITEMS OI
        ON O.ORDER_ID = OI.ORDER_ID

    GROUP BY
        O.ORDER_ID,
        O.ORDER_DATE,
        O.STATUS
)

SELECT
    COUNT(*) AS TOTAL_ORDERS,

    COALESCE(SUM(ORDER_REVENUE), 0)
        ::NUMBER(18,2) AS GROSS_REVENUE,

    COALESCE(AVG(COALESCE(ORDER_REVENUE, 0)), 0)
        ::NUMBER(18,2) AS AVG_ORDER_VALUE,

    COALESCE(SUM(ITEMS_SOLD), 0)
        AS TOTAL_ITEMS_SOLD

FROM ORDER_TOTALS;
