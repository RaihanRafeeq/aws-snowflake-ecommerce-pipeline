
USE WAREHOUSE ECOMMERCE_WH;
USE DATABASE ECOMMERCE_DB;
USE SCHEMA STAGING;

-- Customers: missing important fields
SELECT
    COUNT_IF(CUSTOMER_ID IS NULL) AS NULL_CUSTOMER_IDS,
    COUNT_IF(EMAIL IS NULL OR TRIM(EMAIL) = '') AS MISSING_EMAILS,
    COUNT_IF(CITY IS NULL OR TRIM(CITY) = '') AS MISSING_CITIES,
    COUNT_IF(COUNTRY IS NULL OR TRIM(COUNTRY) = '') AS MISSING_COUNTRIES
FROM STG_CUSTOMERS;

-- Products: missing fields
SELECT
    COUNT_IF(PRODUCT_ID IS NULL) AS NULL_PRODUCT_IDS,
    COUNT_IF(PRODUCT_NAME IS NULL OR TRIM(PRODUCT_NAME) = '') AS MISSING_NAMES,
    COUNT_IF(PRICE IS NULL) AS NULL_PRICES
FROM STG_PRODUCTS;

-- Orders: missing fields
SELECT
    COUNT_IF(ORDER_ID IS NULL) AS NULL_ORDER_IDS,
    COUNT_IF(CUSTOMER_ID IS NULL) AS NULL_CUSTOMER_IDS,
    COUNT_IF(ORDER_DATE IS NULL) AS NULL_ORDER_DATES
FROM STG_ORDERS;

-- Order items: missing fields
SELECT
    COUNT_IF(ORDER_ITEM_ID IS NULL) AS NULL_ITEM_IDS,
    COUNT_IF(ORDER_ID IS NULL) AS NULL_ORDER_IDS,
    COUNT_IF(PRODUCT_ID IS NULL) AS NULL_PRODUCT_IDS,
    COUNT_IF(QUANTITY IS NULL) AS NULL_QUANTITIES,
    COUNT_IF(UNIT_PRICE IS NULL) AS NULL_UNIT_PRICES
FROM STG_ORDER_ITEMS;

-- Payments: missing fields
SELECT
    COUNT_IF(PAYMENT_ID IS NULL) AS NULL_PAYMENT_IDS,
    COUNT_IF(ORDER_ID IS NULL) AS NULL_ORDER_IDS,
    COUNT_IF(AMOUNT IS NULL) AS NULL_AMOUNTS
FROM STG_PAYMENTS;



-- Duplicate customer IDs
SELECT CUSTOMER_ID, COUNT(*) AS DUPLICATE_COUNT
FROM STG_CUSTOMERS
GROUP BY CUSTOMER_ID
HAVING COUNT(*) > 1;

-- Duplicate product IDs
SELECT PRODUCT_ID, COUNT(*) AS DUPLICATE_COUNT
FROM STG_PRODUCTS
GROUP BY PRODUCT_ID
HAVING COUNT(*) > 1;

-- Duplicate order IDs
SELECT ORDER_ID, COUNT(*) AS DUPLICATE_COUNT
FROM STG_ORDERS
GROUP BY ORDER_ID
HAVING COUNT(*) > 1;

-- Duplicate order item IDs
SELECT ORDER_ITEM_ID, COUNT(*) AS DUPLICATE_COUNT
FROM STG_ORDER_ITEMS
GROUP BY ORDER_ITEM_ID
HAVING COUNT(*) > 1;

-- Duplicate payment IDs
SELECT PAYMENT_ID, COUNT(*) AS DUPLICATE_COUNT
FROM STG_PAYMENTS
GROUP BY PAYMENT_ID
HAVING COUNT(*) > 1;
