
CREATE OR REPLACE VIEW VW_ANALYTICS_VALIDATION AS

WITH CHECKS AS (

    -- 1. Customers: RAW vs STAGING
    SELECT
        'CUSTOMER_ROW_COUNT' AS CHECK_NAME,
        (SELECT COUNT(*)
         FROM ECOMMERCE_DB.RAW.CUSTOMERS)::NUMBER(38,2)
            AS EXPECTED_VALUE,
        (SELECT COUNT(*)
         FROM ECOMMERCE_DB.STAGING.STG_CUSTOMERS)::NUMBER(38,2)
            AS ACTUAL_VALUE

    UNION ALL

    -- 2. Products: RAW vs STAGING
    SELECT
        'PRODUCT_ROW_COUNT',
        (SELECT COUNT(*)
         FROM ECOMMERCE_DB.RAW.PRODUCTS),
        (SELECT COUNT(*)
         FROM ECOMMERCE_DB.STAGING.STG_PRODUCTS)

    UNION ALL

    -- 3. Orders: RAW vs STAGING
    SELECT
        'ORDER_ROW_COUNT',
        (SELECT COUNT(*)
         FROM ECOMMERCE_DB.RAW.ORDERS),
        (SELECT COUNT(*)
         FROM ECOMMERCE_DB.STAGING.STG_ORDERS)

    UNION ALL

    -- 4. Order items: RAW vs STAGING
    SELECT
        'ORDER_ITEM_ROW_COUNT',
        (SELECT COUNT(*)
         FROM ECOMMERCE_DB.RAW.ORDER_ITEMS),
        (SELECT COUNT(*)
         FROM ECOMMERCE_DB.STAGING.STG_ORDER_ITEMS)

    UNION ALL

    -- 5. Payments: RAW vs STAGING
    SELECT
        'PAYMENT_ROW_COUNT',
        (SELECT COUNT(*)
         FROM ECOMMERCE_DB.RAW.PAYMENTS),
        (SELECT COUNT(*)
         FROM ECOMMERCE_DB.STAGING.STG_PAYMENTS)

    UNION ALL

    -- 6. Overall revenue vs product revenue
    SELECT
        'PRODUCT_REVENUE',
        (SELECT GROSS_REVENUE
         FROM ECOMMERCE_DB.ANALYTICS.VW_REVENUE_KPIS),
        (SELECT COALESCE(SUM(GROSS_REVENUE), 0)
         FROM ECOMMERCE_DB.ANALYTICS.VW_PRODUCT_PERFORMANCE)

    UNION ALL

    -- 7. Overall revenue vs category revenue
    SELECT
        'CATEGORY_REVENUE',
        (SELECT GROSS_REVENUE
         FROM ECOMMERCE_DB.ANALYTICS.VW_REVENUE_KPIS),
        (SELECT COALESCE(SUM(GROSS_REVENUE), 0)
         FROM ECOMMERCE_DB.ANALYTICS.VW_CATEGORY_PERFORMANCE)

    UNION ALL

    -- 8. Overall revenue vs customer spending
    SELECT
        'CUSTOMER_REVENUE',
        (SELECT GROSS_REVENUE
         FROM ECOMMERCE_DB.ANALYTICS.VW_REVENUE_KPIS),
        (SELECT COALESCE(SUM(TOTAL_SPENT), 0)
         FROM ECOMMERCE_DB.ANALYTICS.VW_CUSTOMER_PERFORMANCE)

    UNION ALL

    -- 9. Overall revenue vs monthly revenue
    SELECT
        'MONTHLY_REVENUE',
        (SELECT GROSS_REVENUE
         FROM ECOMMERCE_DB.ANALYTICS.VW_REVENUE_KPIS),
        (SELECT COALESCE(SUM(GROSS_REVENUE), 0)
         FROM ECOMMERCE_DB.ANALYTICS.VW_MONTHLY_SALES)

    UNION ALL

    -- 10. Customer orders vs overall orders
    SELECT
        'CUSTOMER_ORDER_COUNT',
        (SELECT TOTAL_ORDERS
         FROM ECOMMERCE_DB.ANALYTICS.VW_REVENUE_KPIS),
        (SELECT COALESCE(SUM(TOTAL_ORDERS), 0)
         FROM ECOMMERCE_DB.ANALYTICS.VW_CUSTOMER_PERFORMANCE)

    UNION ALL

    -- 11. Payment counts
    SELECT
        'PAYMENT_COUNT',
        (SELECT COUNT(*)
         FROM ECOMMERCE_DB.STAGING.STG_PAYMENTS),
        (SELECT TOTAL_PAYMENTS
         FROM ECOMMERCE_DB.ANALYTICS.VW_PAYMENT_KPIS)

    UNION ALL

    -- 12. Reconciliation rows vs orders
    SELECT
        'PAYMENT_RECONCILIATION_COUNT',
        (SELECT COUNT(*)
         FROM ECOMMERCE_DB.STAGING.STG_ORDERS),
        (SELECT COUNT(*)
         FROM ECOMMERCE_DB.ANALYTICS.VW_PAYMENT_RECONCILIATION)
)

SELECT
    CHECK_NAME,
    EXPECTED_VALUE,
    ACTUAL_VALUE,

    (ACTUAL_VALUE - EXPECTED_VALUE)
        AS DIFFERENCE,

    CASE
        WHEN EXPECTED_VALUE IS NULL
          OR ACTUAL_VALUE IS NULL
            THEN 'FAIL'
        WHEN ABS(ACTUAL_VALUE - EXPECTED_VALUE) < 0.01
            THEN 'PASS'
        ELSE 'FAIL'
    END AS CHECK_STATUS

FROM CHECKS;
