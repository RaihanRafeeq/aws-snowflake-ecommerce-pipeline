
-- ============================================================
-- 27_create_streams.sql
-- Append-only streams for incremental ingestion
-- ============================================================

USE DATABASE ECOMMERCE_DB;
USE SCHEMA RAW;

CREATE STREAM IF NOT EXISTS CUSTOMERS_STREAM
ON TABLE ECOMMERCE_DB.RAW.CUSTOMERS
APPEND_ONLY = TRUE;

CREATE STREAM IF NOT EXISTS PRODUCTS_STREAM
ON TABLE ECOMMERCE_DB.RAW.PRODUCTS
APPEND_ONLY = TRUE;

CREATE STREAM IF NOT EXISTS ORDERS_STREAM
ON TABLE ECOMMERCE_DB.RAW.ORDERS
APPEND_ONLY = TRUE;

CREATE STREAM IF NOT EXISTS ORDER_ITEMS_STREAM
ON TABLE ECOMMERCE_DB.RAW.ORDER_ITEMS
APPEND_ONLY = TRUE;

CREATE STREAM IF NOT EXISTS PAYMENTS_STREAM
ON TABLE ECOMMERCE_DB.RAW.PAYMENTS
APPEND_ONLY = TRUE;

-- Verify
SHOW STREAMS IN SCHEMA ECOMMERCE_DB.RAW;
