
USE WAREHOUSE ECOMMERCE_WH;
USE DATABASE ECOMMERCE_DB;
USE SCHEMA RAW;

CREATE OR REPLACE TEMPORARY TABLE CUSTOMER_LOAD_TEST (
    CUSTOMER_ID NUMBER(10,0),
    FIRST_NAME VARCHAR(100),
    LAST_NAME VARCHAR(100),
    EMAIL VARCHAR(255),
    CITY VARCHAR(100),
    COUNTRY VARCHAR(100),
    SIGNUP_DATE DATE
);



CREATE OR REPLACE TEMPORARY STAGE CUSTOMER_ERROR_TEST_STAGE
    FILE_FORMAT = (
        TYPE = CSV
        FIELD_DELIMITER = ','
        SKIP_HEADER = 0
        FIELD_OPTIONALLY_ENCLOSED_BY = '"'
        COMPRESSION = NONE
    );

COPY INTO @CUSTOMER_ERROR_TEST_STAGE/invalid_customers.csv
FROM (
    SELECT
        '1001' AS CUSTOMER_ID,
        'John' AS FIRST_NAME,
        'Smith' AS LAST_NAME,
        'john@example.com' AS EMAIL,
        'Dubai' AS CITY,
        'UAE' AS COUNTRY,
        '2026-01-15' AS SIGNUP_DATE

    UNION ALL

    SELECT
        'INVALID_ID',
        'Jane',
        'Doe',
        'jane@example.com',
        'Abu Dhabi',
        'UAE',
        '2026-01-16'
)
FILE_FORMAT = (
    TYPE = CSV
    FIELD_DELIMITER = ','
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    COMPRESSION = NONE
)
HEADER = FALSE
SINGLE = TRUE
OVERWRITE = TRUE;



COPY INTO CUSTOMER_LOAD_TEST
FROM @CUSTOMER_ERROR_TEST_STAGE
FILE_FORMAT = (
    TYPE = CSV
    FIELD_DELIMITER = ','
    SKIP_HEADER = 0
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    COMPRESSION = NONE
)
VALIDATION_MODE = 'RETURN_ALL_ERRORS';



COPY INTO CUSTOMER_LOAD_TEST
FROM @CUSTOMER_ERROR_TEST_STAGE
FILE_FORMAT = (
    TYPE = CSV
    FIELD_DELIMITER = ','
    SKIP_HEADER = 0
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    COMPRESSION = NONE
)
ON_ERROR = 'ABORT_STATEMENT';


DROP STAGE IF EXISTS CUSTOMER_ERROR_TEST_STAGE;
DROP TABLE IF EXISTS CUSTOMER_LOAD_TEST;