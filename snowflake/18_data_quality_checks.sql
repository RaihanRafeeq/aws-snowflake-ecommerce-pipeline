INSERT INTO DATA_QUALITY_RESULTS

SELECT
    'CUSTOMERS_EMAIL_FORMAT',
    'STG_CUSTOMERS',
    COUNT_IF(
        EMAIL IS NOT NULL
        AND EMAIL <> LOWER(TRIM(EMAIL))
    ),
    IFF(
        COUNT_IF(
            EMAIL IS NOT NULL
            AND EMAIL <> LOWER(TRIM(EMAIL))
        ) = 0,
        'PASS', 'FAIL'
    ),
    CURRENT_TIMESTAMP()::TIMESTAMP_NTZ
FROM STG_CUSTOMERS

UNION ALL

SELECT
    'ORDERS_STATUS_FORMAT',
    'STG_ORDERS',
    COUNT_IF(
        STATUS IS NOT NULL
        AND STATUS <> UPPER(TRIM(STATUS))
    ),
    IFF(
        COUNT_IF(
            STATUS IS NOT NULL
            AND STATUS <> UPPER(TRIM(STATUS))
        ) = 0,
        'PASS', 'FAIL'
    ),
    CURRENT_TIMESTAMP()::TIMESTAMP_NTZ
FROM STG_ORDERS;
