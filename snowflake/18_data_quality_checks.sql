
USE WAREHOUSE ECOMMERCE_WH;
USE DATABASE ECOMMERCE_DB;
USE SCHEMA STAGING;

CREATE TABLE IF NOT EXISTS DATA_QUALITY_RESULTS (
    CHECK_NAME VARCHAR(150),
    TABLE_NAME VARCHAR(100),
    FAILED_RECORDS NUMBER,
    CHECK_STATUS VARCHAR(20),
    CHECK_TIMESTAMP TIMESTAMP_NTZ
);



-- Clear previous results so each run shows a fresh snapshot
TRUNCATE TABLE DATA_QUALITY_RESULTS;

INSERT INTO DATA_QUALITY_RESULTS
SELECT
    'CUSTOMERS_NULL_ID',
    'STG_CUSTOMERS',
    COUNT_IF(CUSTOMER_ID IS NULL),
    IFF(COUNT_IF(CUSTOMER_ID IS NULL) = 0, 'PASS', 'FAIL'),
    CURRENT_TIMESTAMP()::TIMESTAMP_NTZ
FROM STG_CUSTOMERS

UNION ALL

SELECT
    'CUSTOMERS_DUPLICATE_ID',
    'STG_CUSTOMERS',
    COUNT(*) - COUNT(DISTINCT CUSTOMER_ID),
    IFF(
        COUNT(*) - COUNT(DISTINCT CUSTOMER_ID) = 0,
        'PASS', 'FAIL'
    ),
    CURRENT_TIMESTAMP()::TIMESTAMP_NTZ
FROM STG_CUSTOMERS

UNION ALL

SELECT
    'PRODUCTS_NULL_ID',
    'STG_PRODUCTS',
    COUNT_IF(PRODUCT_ID IS NULL),
    IFF(COUNT_IF(PRODUCT_ID IS NULL) = 0, 'PASS', 'FAIL'),
    CURRENT_TIMESTAMP()::TIMESTAMP_NTZ
FROM STG_PRODUCTS

UNION ALL

SELECT
    'ORDERS_NULL_ID',
    'STG_ORDERS',
    COUNT_IF(ORDER_ID IS NULL),
    IFF(COUNT_IF(ORDER_ID IS NULL) = 0, 'PASS', 'FAIL'),
    CURRENT_TIMESTAMP()::TIMESTAMP_NTZ
FROM STG_ORDERS

UNION ALL

SELECT
    'ORDER_ITEMS_NULL_ID',
    'STG_ORDER_ITEMS',
    COUNT_IF(ORDER_ITEM_ID IS NULL),
    IFF(COUNT_IF(ORDER_ITEM_ID IS NULL) = 0, 'PASS', 'FAIL'),
    CURRENT_TIMESTAMP()::TIMESTAMP_NTZ
FROM STG_ORDER_ITEMS

UNION ALL

SELECT
    'PAYMENTS_NULL_ID',
    'STG_PAYMENTS',
    COUNT_IF(PAYMENT_ID IS NULL),
    IFF(COUNT_IF(PAYMENT_ID IS NULL) = 0, 'PASS', 'FAIL'),
    CURRENT_TIMESTAMP()::TIMESTAMP_NTZ
FROM STG_PAYMENTS;



INSERT INTO DATA_QUALITY_RESULTS

-- Orders referencing nonexistent customers
SELECT
    'ORDERS_INVALID_CUSTOMER',
    'STG_ORDERS',
    COUNT(*),
    IFF(COUNT(*) = 0, 'PASS', 'FAIL'),
    CURRENT_TIMESTAMP()::TIMESTAMP_NTZ
FROM STG_ORDERS O
LEFT JOIN STG_CUSTOMERS C
    ON O.CUSTOMER_ID = C.CUSTOMER_ID
WHERE C.CUSTOMER_ID IS NULL

UNION ALL

-- Order items referencing nonexistent orders
SELECT
    'ITEMS_INVALID_ORDER',
    'STG_ORDER_ITEMS',
    COUNT(*),
    IFF(COUNT(*) = 0, 'PASS', 'FAIL'),
    CURRENT_TIMESTAMP()::TIMESTAMP_NTZ
FROM STG_ORDER_ITEMS OI
LEFT JOIN STG_ORDERS O
    ON OI.ORDER_ID = O.ORDER_ID
WHERE O.ORDER_ID IS NULL

UNION ALL

-- Order items referencing nonexistent products
SELECT
    'ITEMS_INVALID_PRODUCT',
    'STG_ORDER_ITEMS',
    COUNT(*),
    IFF(COUNT(*) = 0, 'PASS', 'FAIL'),
    CURRENT_TIMESTAMP()::TIMESTAMP_NTZ
FROM STG_ORDER_ITEMS OI
LEFT JOIN STG_PRODUCTS P
    ON OI.PRODUCT_ID = P.PRODUCT_ID
WHERE P.PRODUCT_ID IS NULL

UNION ALL

-- Payments referencing nonexistent orders
SELECT
    'PAYMENTS_INVALID_ORDER',
    'STG_PAYMENTS',
    COUNT(*),
    IFF(COUNT(*) = 0, 'PASS', 'FAIL'),
    CURRENT_TIMESTAMP()::TIMESTAMP_NTZ
FROM STG_PAYMENTS P
LEFT JOIN STG_ORDERS O
    ON P.ORDER_ID = O.ORDER_ID
WHERE O.ORDER_ID IS NULL;



