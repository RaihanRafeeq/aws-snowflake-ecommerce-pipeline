
-- Step 10.1: Create staging tables

USE WAREHOUSE ECOMMERCE_WH;
USE DATABASE ECOMMERCE_DB;
USE SCHEMA STAGING;

-- Customers
CREATE TABLE IF NOT EXISTS STG_CUSTOMERS
LIKE ECOMMERCE_DB.RAW.CUSTOMERS;

-- Products
CREATE TABLE IF NOT EXISTS STG_PRODUCTS
LIKE ECOMMERCE_DB.RAW.PRODUCTS;

-- Orders
CREATE TABLE IF NOT EXISTS STG_ORDERS
LIKE ECOMMERCE_DB.RAW.ORDERS;

-- Order Items
CREATE TABLE IF NOT EXISTS STG_ORDER_ITEMS
LIKE ECOMMERCE_DB.RAW.ORDER_ITEMS;

-- Payments
CREATE TABLE IF NOT EXISTS STG_PAYMENTS
LIKE ECOMMERCE_DB.RAW.PAYMENTS;
