
USE WAREHOUSE ECOMMERCE_WH;
USE DATABASE ECOMMERCE_DB;
USE SCHEMA RAW;

WITH EXPECTED_COUNTS AS (
    SELECT 'CUSTOMERS' AS TABLE_NAME, 1000 AS EXPECTED_COUNT
    UNION ALL SELECT 'PRODUCTS', 100
    UNION ALL SELECT 'ORDERS', 5000
    UNION ALL SELECT 'ORDER_ITEMS', 15033
    UNION ALL SELECT 'PAYMENTS', 5000
),
ACTUAL_COUNTS AS (
    SELECT 'CUSTOMERS' AS TABLE_NAME, COUNT(*) AS ACTUAL_COUNT
    FROM CUSTOMERS

    UNION ALL

    SELECT 'PRODUCTS', COUNT(*)
    FROM PRODUCTS

    UNION ALL

    SELECT 'ORDERS', COUNT(*)
    FROM ORDERS

    UNION ALL

    SELECT 'ORDER_ITEMS', COUNT(*)
    FROM ORDER_ITEMS

    UNION ALL

    SELECT 'PAYMENTS', COUNT(*)
    FROM PAYMENTS
)
SELECT
    e.TABLE_NAME,
    e.EXPECTED_COUNT,
    a.ACTUAL_COUNT,
    a.ACTUAL_COUNT - e.EXPECTED_COUNT AS DIFFERENCE,
    CASE
        WHEN a.ACTUAL_COUNT = e.EXPECTED_COUNT THEN 'PASS'
        ELSE 'FAIL'
    END AS VALIDATION_STATUS
FROM EXPECTED_COUNTS e
JOIN ACTUAL_COUNTS a
    ON e.TABLE_NAME = a.TABLE_NAME
ORDER BY e.TABLE_NAME;
