
CREATE OR REPLACE VIEW VW_PAYMENT_PERFORMANCE AS

SELECT
    COALESCE(PAYMENT_METHOD, 'UNKNOWN')
        AS PAYMENT_METHOD,

    COALESCE(PAYMENT_STATUS, 'UNKNOWN')
        AS PAYMENT_STATUS,

    COUNT(*) AS TOTAL_PAYMENTS,

    COUNT(DISTINCT ORDER_ID)
        AS DISTINCT_ORDERS,

    COALESCE(SUM(AMOUNT), 0)::NUMBER(18,2)
        AS TOTAL_PAYMENT_AMOUNT,

    COALESCE(AVG(AMOUNT), 0)::NUMBER(18,2)
        AS AVG_PAYMENT_AMOUNT

FROM ECOMMERCE_DB.STAGING.STG_PAYMENTS

GROUP BY
    COALESCE(PAYMENT_METHOD, 'UNKNOWN'),
    COALESCE(PAYMENT_STATUS, 'UNKNOWN');


CREATE OR REPLACE VIEW VW_PAYMENT_KPIS AS

WITH CLASSIFIED_PAYMENTS AS (
    SELECT
        PAYMENT_ID,
        ORDER_ID,
        AMOUNT,

        CASE
            WHEN PAYMENT_STATUS IN (
                'SUCCESS',
                'SUCCESSFUL',
                'COMPLETED',
                'PAID'
            )
            THEN 1
            ELSE 0
        END AS IS_SUCCESSFUL

    FROM ECOMMERCE_DB.STAGING.STG_PAYMENTS
)

SELECT
    COUNT(*) AS TOTAL_PAYMENTS,

    COUNT_IF(IS_SUCCESSFUL = 1)
        AS SUCCESSFUL_PAYMENTS,

    COUNT_IF(IS_SUCCESSFUL = 0)
        AS OTHER_PAYMENTS,

    ROUND(
        100.0 * COUNT_IF(IS_SUCCESSFUL = 1)
        / NULLIF(COUNT(*), 0),
        2
    ) AS PAYMENT_SUCCESS_RATE_PERCENT,

    COALESCE(SUM(AMOUNT), 0)::NUMBER(18,2)
        AS TOTAL_RECORDED_AMOUNT,

    COALESCE(
        SUM(IFF(IS_SUCCESSFUL = 1, AMOUNT, 0)),
        0
    )::NUMBER(18,2)
        AS SUCCESSFUL_PAYMENT_AMOUNT

FROM CLASSIFIED_PAYMENTS;


CREATE OR REPLACE VIEW VW_PAYMENT_RECONCILIATION AS

WITH ORDER_TOTALS AS (
    SELECT
        O.ORDER_ID,
        O.ORDER_DATE,
        O.STATUS AS ORDER_STATUS,

        COALESCE(
            SUM(OI.QUANTITY * OI.UNIT_PRICE),
            0
        ) AS ORDER_AMOUNT

    FROM ECOMMERCE_DB.STAGING.STG_ORDERS O

    LEFT JOIN ECOMMERCE_DB.STAGING.STG_ORDER_ITEMS OI
        ON O.ORDER_ID = OI.ORDER_ID

    GROUP BY
        O.ORDER_ID,
        O.ORDER_DATE,
        O.STATUS
),

PAYMENT_TOTALS AS (
    SELECT
        ORDER_ID,

        COUNT(*) AS PAYMENT_COUNT,

        SUM(AMOUNT) AS RECORDED_PAYMENT_AMOUNT,

        SUM(
            CASE
                WHEN PAYMENT_STATUS IN (
                    'SUCCESS',
                    'SUCCESSFUL',
                    'COMPLETED',
                    'PAID'
                )
                THEN AMOUNT
                ELSE 0
            END
        ) AS SUCCESSFUL_PAYMENT_AMOUNT

    FROM ECOMMERCE_DB.STAGING.STG_PAYMENTS

    GROUP BY ORDER_ID
)

SELECT
    O.ORDER_ID,
    O.ORDER_DATE,
    O.ORDER_STATUS,

    O.ORDER_AMOUNT::NUMBER(18,2)
        AS ORDER_AMOUNT,

    COALESCE(P.PAYMENT_COUNT, 0)
        AS PAYMENT_COUNT,

    COALESCE(P.RECORDED_PAYMENT_AMOUNT, 0)
        ::NUMBER(18,2) AS RECORDED_PAYMENT_AMOUNT,

    COALESCE(P.SUCCESSFUL_PAYMENT_AMOUNT, 0)
        ::NUMBER(18,2) AS SUCCESSFUL_PAYMENT_AMOUNT,

    (
        O.ORDER_AMOUNT
        - COALESCE(P.SUCCESSFUL_PAYMENT_AMOUNT, 0)
    )::NUMBER(18,2) AS PAYMENT_DIFFERENCE,

    CASE
        WHEN P.ORDER_ID IS NULL
            THEN 'MISSING_PAYMENT'

        WHEN ABS(
            O.ORDER_AMOUNT
            - COALESCE(P.SUCCESSFUL_PAYMENT_AMOUNT, 0)
        ) < 0.01
            THEN 'MATCHED'

        ELSE 'MISMATCH'
    END AS RECONCILIATION_STATUS

FROM ORDER_TOTALS O

LEFT JOIN PAYMENT_TOTALS P
    ON O.ORDER_ID = P.ORDER_ID;
