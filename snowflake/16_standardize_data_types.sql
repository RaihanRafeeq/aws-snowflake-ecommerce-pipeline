
USE DATABASE ECOMMERCE_DB;

-- 1. Customers
INSERT INTO STAGING.STG_CUSTOMERS
SELECT
    CUSTOMER_ID,
    TRIM(FIRST_NAME),
    TRIM(LAST_NAME),
    LOWER(TRIM(EMAIL)),
    TRIM(CITY),
    TRIM(COUNTRY),
    SIGNUP_DATE
FROM RAW.CUSTOMERS;

-- 2. Products
INSERT INTO STAGING.STG_PRODUCTS
SELECT
    PRODUCT_ID,
    TRIM(PRODUCT_NAME),
    TRIM(CATEGORY),
    PRICE::NUMBER(12,2)
FROM RAW.PRODUCTS;

-- 3. Orders
INSERT INTO STAGING.STG_ORDERS
SELECT
    ORDER_ID,
    CUSTOMER_ID,
    ORDER_DATE,
    UPPER(TRIM(STATUS))
FROM RAW.ORDERS;

-- 4. Order Items
INSERT INTO STAGING.STG_ORDER_ITEMS
SELECT
    ORDER_ITEM_ID,
    ORDER_ID,
    PRODUCT_ID,
    QUANTITY::NUMBER(10,0),
    UNIT_PRICE::NUMBER(12,2)
FROM RAW.ORDER_ITEMS;

-- 5. Payments
INSERT INTO STAGING.STG_PAYMENTS
SELECT
    PAYMENT_ID,
    ORDER_ID,
    UPPER(TRIM(PAYMENT_METHOD)),
    AMOUNT::NUMBER(12,2),
    UPPER(TRIM(PAYMENT_STATUS))
FROM RAW.PAYMENTS;
