
-- ============================================================
-- 26_create_snowpipes.sql
-- Snowpipe auto-ingestion from S3 to RAW tables
-- Prerequisites:
--   ECOMMERCE_AUTO_INGEST_STAGE
--   ECOMMERCE_CSV_FORMAT
--   RAW tables
-- S3 event notifications must be configured separately.
-- ============================================================

USE DATABASE ECOMMERCE_DB;
USE SCHEMA RAW;

CREATE PIPE IF NOT EXISTS CUSTOMERS_PIPE
AUTO_INGEST = TRUE
AS
COPY INTO ECOMMERCE_DB.RAW.CUSTOMERS
FROM @ECOMMERCE_DB.RAW.ECOMMERCE_AUTO_INGEST_STAGE/customers/
FILE_FORMAT = (
    FORMAT_NAME = 'ECOMMERCE_DB.RAW.ECOMMERCE_CSV_FORMAT'
);

