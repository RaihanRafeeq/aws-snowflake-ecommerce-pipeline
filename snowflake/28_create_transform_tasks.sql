
-- ============================================================
-- 28_create_transform_tasks.sql
-- Incremental RAW -> STAGING transformations
-- Schedule: Every 15 minutes
-- Warehouse: ECOMMERCE_WH
--
-- Tasks are created SUSPENDED by default.
-- Resume them only when testing or operating the pipeline.
-- ============================================================

USE DATABASE ECOMMERCE_DB;
USE SCHEMA STAGING;

-- CUSTOMERS
CREATE TASK IF NOT EXISTS CUSTOMERS_TRANSFORM_TASK
WAREHOUSE = ECOMMERCE_WH
SCHEDULE = '15 MINUTE'
WHEN SYSTEM$STREAM_HAS_DATA(
    'ECOMMERCE_DB.RAW.CUSTOMERS_STREAM'
)
AS
MERGE INTO ECOMMERCE_DB.STAGING.STG_CUSTOMERS t
USING (
    SELECT
        CUSTOMER_ID, FIRST_NAME, LAST_NAME,
        EMAIL, CITY, COUNTRY, SIGNUP_DATE
    FROM ECOMMERCE_DB.RAW.CUSTOMERS_STREAM
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY CUSTOMER_ID
        ORDER BY METADATA$ROW_ID DESC
    ) = 1
) s
ON t.CUSTOMER_ID = s.CUSTOMER_ID
WHEN MATCHED THEN UPDATE SET
    t.FIRST_NAME = s.FIRST_NAME,
    t.LAST_NAME = s.LAST_NAME,
    t.EMAIL = s.EMAIL,
    t.CITY = s.CITY,
    t.COUNTRY = s.COUNTRY,
    t.SIGNUP_DATE = s.SIGNUP_DATE
WHEN NOT MATCHED THEN INSERT (
    CUSTOMER_ID, FIRST_NAME, LAST_NAME,
    EMAIL, CITY, COUNTRY, SIGNUP_DATE
)
VALUES (
    s.CUSTOMER_ID, s.FIRST_NAME, s.LAST_NAME,
    s.EMAIL, s.CITY, s.COUNTRY, s.SIGNUP_DATE
);

