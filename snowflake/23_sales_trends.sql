
CREATE OR REPLACE VIEW VW_MONTHLY_SALES AS

SELECT
    DATE_TRUNC('MONTH', ORDER_DATE)::DATE
        AS SALES_MONTH,

    SUM(TOTAL_ORDERS)
        AS TOTAL_ORDERS,

    SUM(TOTAL_ITEMS_SOLD)
        AS TOTAL_ITEMS_SOLD,

    SUM(GROSS_REVENUE)::NUMBER(18,2)
        AS GROSS_REVENUE,

    (
        SUM(GROSS_REVENUE)
        / NULLIF(SUM(TOTAL_ORDERS), 0)
    )::NUMBER(18,2)
        AS AVG_ORDER_VALUE

FROM ECOMMERCE_DB.ANALYTICS.VW_DAILY_SALES

GROUP BY DATE_TRUNC('MONTH', ORDER_DATE)::DATE;



CREATE OR REPLACE VIEW VW_MONTHLY_GROWTH AS

WITH MONTHLY_COMPARISON AS (
    SELECT
        SALES_MONTH,
        TOTAL_ORDERS,
        TOTAL_ITEMS_SOLD,
        GROSS_REVENUE,
        AVG_ORDER_VALUE,

        LAG(SALES_MONTH) OVER (
            ORDER BY SALES_MONTH
        ) AS PREVIOUS_MONTH,

        LAG(GROSS_REVENUE) OVER (
            ORDER BY SALES_MONTH
        ) AS PREVIOUS_MONTH_REVENUE,

        LAG(TOTAL_ORDERS) OVER (
            ORDER BY SALES_MONTH
        ) AS PREVIOUS_MONTH_ORDERS

    FROM ECOMMERCE_DB.ANALYTICS.VW_MONTHLY_SALES
)

SELECT
    SALES_MONTH,
    TOTAL_ORDERS,
    TOTAL_ITEMS_SOLD,
    GROSS_REVENUE,
    AVG_ORDER_VALUE,

    CASE
        WHEN PREVIOUS_MONTH =
             DATEADD('MONTH', -1, SALES_MONTH)
        THEN PREVIOUS_MONTH_REVENUE
        ELSE NULL
    END AS PREVIOUS_MONTH_REVENUE,

    CASE
        WHEN PREVIOUS_MONTH =
             DATEADD('MONTH', -1, SALES_MONTH)
        THEN ROUND(
            100.0 * (
                GROSS_REVENUE - PREVIOUS_MONTH_REVENUE
            ) / NULLIF(PREVIOUS_MONTH_REVENUE, 0),
            2
        )
        ELSE NULL
    END AS REVENUE_GROWTH_PERCENT,

    CASE
        WHEN PREVIOUS_MONTH =
             DATEADD('MONTH', -1, SALES_MONTH)
        THEN ROUND(
            100.0 * (
                TOTAL_ORDERS - PREVIOUS_MONTH_ORDERS
            ) / NULLIF(PREVIOUS_MONTH_ORDERS, 0),
            2
        )
        ELSE NULL
    END AS ORDER_GROWTH_PERCENT

FROM MONTHLY_COMPARISON;
